def build(file, doc_id, title, pages):
    def footer(canvas, doc):
        canvas.setFont("Helvetica", 8)
        canvas.setFillColorRGB(0.45, 0.45, 0.45)
        canvas.drawString(50, 28, f"{doc_id} | {title} | FICTIONAL - FOR EDUCATIONAL USE ONLY")
        canvas.drawRightString(A4[0] - 50, 28, f"Page {doc.page}")

    story = [Paragraph(f"{title} ({doc_id})", styles["Title"]),
             Paragraph("Version 1.0 | Fictional document created for the FinGuard AI portfolio project.", NOTE),
             Spacer(1, 8)]
    for i, page in enumerate(pages):
        for level, heading, paras in page:
            story.append(Paragraph(heading, H1 if level == 1 else H2))
            for p in paras:
                story.append(Paragraph(p, BODY))
        if i < len(pages) - 1:
            story.append(PageBreak())
    SimpleDocTemplate(str(OUT / file), pagesize=A4, title=title,
                      leftMargin=50, rightMargin=50, topMargin=50,
                      bottomMargin=50).build(story, onFirstPage=footer, onLaterPages=footer)


